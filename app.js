// ============================================================
// ANSWER
// ============================================================

function answer(selected) {

  const q =
    session.currentQuestion;

  const correct =
    selected === q.answer;

  document
    .querySelectorAll('.answer')
    .forEach((button, index) => {

      button.disabled = true;

      if (index === q.answer) {
        button.classList.add('correct');
      }

      if (
        index === selected &&
        index !== q.answer
      ) {
        button.classList.add('wrong');
      }

    });


  session.answers.push({
    q,
    correct
  });


  store.done++;

  store.xp += correct ? 10 : 2;


  if (correct) {

    store.correct++;

  } else if (
    !store.mistakes.includes(q.id)
  ) {

    store.mistakes.push(q.id);

  }


  save();


  const feedback =
    document.querySelector('#feedback');


  if (session.mode === 'mock') {

    feedback.innerHTML = `
      <div class="next-row">

        <button
          class="primary"
          onclick="next()"
        >
          ${
            session.index ===
            session.list.length - 1
              ? 'Finish exam'
              : 'Next question →'
          }
        </button>

      </div>
    `;

  } else {

    feedback.innerHTML = `
      <div class="
        feedback
        ${correct ? '' : 'bad'}
      ">

        <b>
          ${correct
            ? '✅ Correct!'
            : '❌ Not quite'}
        </b>

        ${q.explanation}

      </div>

      <div class="next-row">

        <button
          class="primary"
          onclick="next()"
        >
          ${
            session.index ===
            session.list.length - 1
              ? 'See results'
              : 'Next →'
          }
        </button>

      </div>
    `;
  }
}


// ============================================================
// NEXT
// ============================================================

function next() {

  session.index++;

  if (
    session.index <
    session.list.length
  ) {

    renderQuestion();

  } else {

    finish();

  }
}


// ============================================================
// FINISH
// ============================================================

function finish() {

  if (session.timer) {
    clearInterval(session.timer);
    session.timer = null;
  }


  if (!session.answers.length) {
    home();
    return;
  }


  const score =
    session.answers.filter(
      x => x.correct
    ).length;

  const total =
    session.list.length;

  const percent =
    Math.round(
      score / total * 100
    );


  if (session.mode === 'mock') {

    store.history.unshift({
      score,
      total,
      date: new Date()
        .toLocaleDateString()
    });

  }


  save();


  const byTopic = {};


  session.answers.forEach(
    ({ q, correct }) => {

      if (!byTopic[q.topic]) {
        byTopic[q.topic] = [0, 0];
      }

      byTopic[q.topic][1]++;

      if (correct) {
        byTopic[q.topic][0]++;
      }

    }
  );


  document.querySelector('#app').innerHTML = `
    <div class="shell">

      ${nav()}

      <div class="result">

        <button
          class="back"
          onclick="home()"
        >
          ← Home
        </button>

        <div class="result-score">

          <div
            class="eyebrow"
            style="color:#ffcf46"
          >
            ${session.title} complete
          </div>

          <h2>
            ${score} / ${total}
            — ${percent}%
            ${percent >= 75 ? '✅' : '❌'}
          </h2>

          <p>
            ${
              session.mode === 'mock'
                ? 'Pass mark: 75%'
                : 'Keep practising — you are building the habits that matter.'
            }
          </p>

        </div>


        <table class="score-table">

          <thead>
            <tr>
              <th>Topic</th>
              <th>Score</th>
            </tr>
          </thead>

          <tbody>

            ${
              Object.entries(byTopic)
                .map(([topic, [correct, total]]) => `
                  <tr>
                    <td>${topic}</td>
                    <td>${correct}/${total}</td>
                  </tr>
                `)
                .join('')
            }

          </tbody>

        </table>


        <div
          class="cta"
          style="margin-top:22px"
        >

          <button
            class="primary"
            onclick="showTopics()"
          >
            Revise these topics →
          </button>

          <button
            class="secondary"
            onclick="startMock()"
          >
            Another mock
          </button>

        </div>

      </div>

    </div>
  `;
}
